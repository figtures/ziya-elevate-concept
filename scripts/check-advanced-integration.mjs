import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {buildSync} from 'esbuild';
import {createRequire} from 'node:module';
import vm from 'node:vm';
import {parseHTML} from 'linkedom';
import {applyContent} from '../cms/render.mjs';
import {deriveNavigation} from '../cms/navigation.mjs';
import {deriveCollection} from '../cms/collections.mjs';
import {experienceDefaults} from '../cms/experience.mjs';
const data=name=>JSON.parse(readFileSync('cms/'+name+'.json','utf8'));
const seed=data('seed'),catalog=data('catalog'),templates=data('templates'),config=data('config'),styles=data('styles');
const bundled=buildSync({entryPoints:['cms/server.ts'],bundle:true,write:false,format:'cjs',platform:'node',packages:'external'}).outputFiles[0].text;
const module={exports:{}};vm.runInNewContext(bundled,{module,exports:module.exports,require:createRequire(import.meta.url),URL,AbortSignal,console});
const render=module.exports.render;
const base=route=>structuredClone(seed.find(p=>p.route===route));
const documentFor=payload=>{const {document}=parseHTML(templates[payload.template]);applyContent(document,payload,catalog[payload.template],{global:payload.kind==='global'});return document;};
const shared=base('/_global/');shared.navigation=deriveNavigation(documentFor(shared));shared.navigation.primary[0].label='Yönetilen ana bağlantı';shared.navigation.primary[0].children=[{id:'nested-integration',label:'Kitaplar',href:'/kitaplar/',hidden:false,newTab:false}];shared.experience={floating:{enabled:true,label:'Yönetilen iletişim',href:'/iletisim/?konu=keynote'},playback:{pauseLabel:'Sahneyi duraklat',playLabel:'Sahneyi oynat'}};
const book=base('/kitaplar/');book.robots='noindex';
let doc=parseHTML(render(book,shared)).document;
assert.equal(doc.querySelector('header .nav-links a').textContent,'Yönetilen ana bağlantı');
assert(doc.querySelector('header [href="/kitaplar/"]'));
assert.equal(doc.querySelector('.ask-ziya .control-label').textContent,'Yönetilen iletişim');
assert(doc.querySelector('meta[name="robots"]').content.startsWith('noindex'));
const stylesheets=[...doc.querySelectorAll('link[rel="stylesheet"]')].map(e=>e.getAttribute('href'));
assert.equal(stylesheets.length,2,'A managed menu must retain one original CSS bundle plus its menu extension');
assert(stylesheets.some(href=>Object.values(styles).some(s=>s.href===href)));
assert(stylesheets.some(href=>/^\/assets\/cms-navigation.css\?v=[a-f0-9]{12}$/.test(href)));
assert(doc.querySelector('script[src^="/assets/cms-navigation.js?v="]'));
const home=base('/');home.experience=experienceDefaults(documentFor(home),home);home.experience.playlist.reverse();
doc=parseHTML(render(home,shared)).document;
assert.deepEqual([...doc.querySelectorAll('[data-hero-clip]')].map(v=>v.dataset.src),home.experience.playlist.map(v=>v.src));
assert([...doc.querySelectorAll('[data-hero-clip]')].every(v=>!v.getAttribute('src')&&v.getAttribute('preload')==='none'));
assert.equal(doc.querySelector('.video-toggle').dataset.pauseLabel,'Sahneyi duraklat');
assert(doc.querySelector('script[src^="/assets/tedx-hero.js?v="]'));
const contact=base('/iletisim/');
doc=parseHTML(render(contact,shared)).document;
assert(!doc.querySelector('.contact-form-wrap > .hero-note').textContent.includes('kaydedilmez'));
assert(doc.querySelector('script[src^="/assets/cms-contact.js?v="]'));
contact.experience={contact:{phone:'905001234567',submitLabel:'Özel talebi gönder',privacyText:'Talebiniz yanıtlanmak için kaydedilir.'}};
doc=parseHTML(render(contact,shared)).document;
assert.equal(doc.querySelector('#contactForm [type="submit"]').textContent,'Özel talebi gönder');
assert.equal(doc.querySelector('#sendWhatsApp').getAttribute('href'),'https://wa.me/905001234567');
assert.equal(JSON.parse(doc.getElementById('cms-contact-content').textContent).phone,'905001234567');
for(const route of ['/makaleler/','/hayattan-notlar/']){
 const archive=base(route),kind=route==='/makaleler/'?'article':'note';archive.collection=deriveCollection(documentFor(archive),route);archive.collection.categories[0].items.reverse();archive.collection.categories[0].items[0].label='Yönetilen liste başlığı';archive.collection.categories[0].items[1].hidden=true;
 const entries=seed.filter(p=>p.kind===kind).map(p=>({route:p.route,kind,title:p.title}));doc=parseHTML(render(archive,shared,entries)).document;
 const links=[...doc.querySelectorAll('.post-list a')];assert.equal(links[0].textContent.includes('Yönetilen liste başlığı'),true);assert(!links.some(a=>a.getAttribute('href')===archive.collection.categories[0].items[1].route));
 const entities=[...doc.querySelectorAll('script[type="application/ld+json"]')].flatMap(s=>JSON.parse(s.textContent)['@graph']||[]),list=entities.find(e=>e['@type']==='ItemList');
 assert.deepEqual(list.itemListElement.map(e=>new URL(e.item.url).pathname),links.map(a=>a.getAttribute('href')));
}
const test=base('/testler/kafa-yapisi-testi/');test.experience={testUI:{previousLabel:'Bir önceki soruya dön',reportTitle:'Kişisel değerlendirme'}};doc=parseHTML(render(test,shared)).document;
assert.equal(doc.getElementById('previousQuestion').textContent,'Bir önceki soruya dön');assert.equal(JSON.parse(doc.getElementById('cms-test-content').textContent).reportTitle,'Kişisel değerlendirme');
assert.equal(test.test.questions.length,20);
console.log('PASS: full server pipeline retains CSS bundling, managed shared navigation/assets, video playlist/playback controls, truthful contact defaults and saved overrides, archive+schema order and 20-question test interface.');

import assert from 'node:assert/strict';
import fs from 'node:fs';
import {parseHTML} from 'linkedom';
import {transformSync} from 'esbuild';
import {applyHomeLayout} from '../cms/home-layout.mjs';

const templates=JSON.parse(fs.readFileSync('cms/templates.json','utf8'));
const {document}=parseHTML(templates['/']);
const wrap=document.querySelector('.ed-home-books > .wrap');
const heading=wrap.querySelector('.ed-heading'),action=wrap.querySelector(':scope > a.ed-link'),note=wrap.querySelector(':scope > .depth-note');
const originalIDs=[...wrap.querySelectorAll('[data-cms-node]')].map(el=>el.getAttribute('data-cms-node')).sort();
action.querySelector('span').textContent='Kitap koleksiyonunu keşfet';
action.setAttribute('href','/kitaplar/#koleksiyon');
const cards=wrap.querySelector('.home-book-shelf').outerHTML;
applyHomeLayout(document,'/');
const row=wrap.querySelector('.home-books-heading');
assert.equal(row.children[0],heading);
assert.equal(row.children[1],action);
assert.equal(heading.lastElementChild,note);
assert.equal(action.textContent.trim(),'Kitap koleksiyonunu keşfet');
assert.equal(action.getAttribute('href'),'/kitaplar/#koleksiyon');
assert.equal(wrap.querySelector('.home-book-shelf').outerHTML,cards);
assert.deepEqual([...wrap.querySelectorAll('[data-cms-node]')].map(el=>el.getAttribute('data-cms-node')).sort(),originalIDs);
const once=wrap.outerHTML;applyHomeLayout(document,'/');assert.equal(wrap.outerHTML,once);
const archive=parseHTML(templates['/kitaplar/']).document,before=archive.toString();applyHomeLayout(archive,'/kitaplar/');assert.equal(archive.toString(),before);
const empty=parseHTML('<html><body><main></main></body></html>').document;assert.doesNotThrow(()=>applyHomeLayout(empty,'/'));
for(const path of ['website/assets/home-content.css','src/references/reference-slider.css'])assert.equal(transformSync(fs.readFileSync(path,'utf8'),{loader:'css'}).warnings.length,0);
assert.equal(fs.readFileSync('website/assets/home-content.css','utf8'),fs.readFileSync('public/assets/home-content.css','utf8'));
console.log('PASS: homepage action/metadata grouping preserves edited labels, links, cards, CMS identities, idempotence and other pages; scoped CSS parses and mirrors agree.');
